/* =========================================
   OPEN TESTS
========================================= */

function openTests(type) {

  if (type === "practice") {

    alert("Practice Tests will open here.");
    return;

  }


  if (type === "mock") {

    alert("Mock Tests will open here.");
    return;

  }


  if (type === "pyq") {

    alert("PYQ Tests will open here.");
    return;

  }

}


